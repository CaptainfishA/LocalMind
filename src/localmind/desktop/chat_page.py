"""WeChat workspace presentation, separate from synchronization and credentials."""

from PySide6.QtCore import QDate, Qt
from PySide6.QtWidgets import (
    QAbstractItemView, QCheckBox, QComboBox, QDateEdit, QFormLayout, QHBoxLayout,
    QLabel, QLineEdit, QProgressBar, QSpinBox, QStyle, QTabWidget, QToolButton,
    QVBoxLayout, QWidget,
)


def build_chat_page(self, host):
    from .widgets import icon
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(24, 20, 24, 20)
    layout.setSpacing(12)
    heading_row = QHBoxLayout()
    heading = QLabel("数据连接")
    heading.setObjectName("sectionTitle")
    self.overview = QLabel()
    self.overview.setObjectName("mutedText")
    self.connection_status = QLabel("未连接")
    self.connection_status.setObjectName("connectionStatus")
    heading_row.addWidget(heading)
    heading_row.addWidget(self.overview, 1)
    heading_row.addWidget(self.connection_status)
    layout.addLayout(heading_row)
    self.url = QLineEdit(host.db.get_setting("weflow_url", "http://127.0.0.1:5031"))
    self.token = QLineEdit()
    self.token.setEchoMode(QLineEdit.EchoMode.Password)
    self.token.setPlaceholderText("Alpha API Token")
    self.token.setAccessibleName("Alpha API Token")
    self.token.setToolTip("仅在本次运行内存中保存，不写入本地索引")
    self.accounts = QComboBox()
    self.accounts.addItem("当前账号（自动）", None)
    self.accounts.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    self.accounts.setMinimumWidth(180)
    self.accounts.setMaximumWidth(230)
    connection = QHBoxLayout()
    connection.addWidget(QLabel("访问凭证"))
    connection.addWidget(self.token, 1)
    connection.addWidget(self.accounts)
    self.connect_button = self.button("连接", QStyle.StandardPixmap.SP_BrowserReload, self.load_sessions)
    self.connect_button.setMinimumWidth(90)
    self.connect_button.setToolTip("验证连接并刷新账号、会话列表")
    connection.addWidget(self.connect_button)
    layout.addLayout(connection)

    self.period = QComboBox()
    for label, days in [("近 30 天", 30), ("近 90 天", 90), ("全部历史", 0), ("自定义", -1)]:
        self.period.addItem(label, days)
    self.period.setFixedWidth(125)
    self.period.setToolTip("全部历史仍受单会话累计 20000 条 / 20 MB 上限约束，超限会明确标记失败")
    self.start_date = QDateEdit(QDate.currentDate().addDays(-30))
    saved = QDate.fromString(host.db.get_setting("weflow_index_start", ""), "yyyy-MM-dd")
    if saved.isValid() and saved <= QDate.currentDate():
        self.start_date.setDate(saved)
        if saved != QDate.currentDate().addDays(-30):
            self.period.setCurrentIndex(2 if saved == QDate(1970, 1, 1) else 3)
    self.start_date.setDisplayFormat("yyyy-MM-dd")
    self.start_date.setCalendarPopup(True)
    self.start_date.setMinimumDate(QDate(1970, 1, 1))
    self.start_date.setMaximumDate(QDate.currentDate())
    self.start_date.setFixedWidth(140)
    self.scope_label = QLabel("选择会话")
    self.scope_label.setObjectName("scopeLabel")
    self.sync_button = self.button("一键建立索引", QStyle.StandardPixmap.SP_ArrowDown, self.sync)
    self.sync_button.setObjectName("primaryButton")
    self.sync_button.setIcon(icon("download", "#ffffff"))
    self.sync_button.setMinimumWidth(160)
    self.cancel_button = self.button("暂停", QStyle.StandardPixmap.SP_MediaPause, self.pause)
    self.cancel_button.setText("")
    self.cancel_button.setAccessibleName("暂停同步")
    self.cancel_button.setFixedWidth(36)
    self.cancel_button.setEnabled(False)
    commands = QHBoxLayout()
    for widget in [self.scope_label, self.period, self.start_date, QLabel("至今")]:
        commands.addWidget(widget)
    commands.addStretch()
    commands.addWidget(self.sync_button)
    commands.addWidget(self.cancel_button)
    layout.addLayout(commands)
    self.auto = QCheckBox("自动更新（5 分钟）")
    self.advanced_button = QToolButton()
    self.advanced_button.setText("高级设置")
    self.advanced_button.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
    self.advanced_button.setArrowType(Qt.ArrowType.RightArrow)
    self.advanced_button.setCheckable(True)
    options = QHBoxLayout()
    options.addWidget(self.auto)
    options.addStretch()
    options.addWidget(self.advanced_button)
    layout.addLayout(options)

    self.advanced = QWidget()
    advanced = QVBoxLayout(self.advanced)
    advanced.setContentsMargins(0, 0, 0, 0)
    form = QFormLayout()
    form.addRow("API 地址", self.url)
    self.file_root = QLineEdit(host.db.get_setting("wechat_file_root", ""))
    self.file_root.setReadOnly(True)
    self.file_root.setPlaceholderText("未配置")
    root_row = QHBoxLayout()
    root_row.addWidget(self.file_root, 1)
    self.choose_root_button = self.button("选择目录", QStyle.StandardPixmap.SP_DirOpenIcon, self.choose_file_root)
    self.choose_root_button.setToolTip("选择微信设置中显示的文件存储目录；只查文件名，不进行全文索引")
    self.clear_root_button = self.button("", QStyle.StandardPixmap.SP_DialogResetButton, self.clear_file_root)
    self.clear_root_button.setToolTip("取消微信文件目录")
    root_row.addWidget(self.choose_root_button)
    root_row.addWidget(self.clear_root_button)
    form.addRow("微信文件目录", root_row)
    advanced.addLayout(form)
    self.single_session = QCheckBox("仅指定会话")
    self.keyword = QLineEdit()
    self.keyword.setPlaceholderText("筛选会话名称")
    self.keyword.textChanged.connect(self.filter_sessions)
    self.sessions = QComboBox()
    self.sessions.setMinimumWidth(160)
    self.sessions.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    single_row = QHBoxLayout()
    single_row.addWidget(self.single_session)
    single_row.addWidget(self.keyword, 1)
    single_row.addWidget(self.sessions, 2)
    advanced.addLayout(single_row)
    self.max_messages = QSpinBox()
    self.max_messages.setRange(1, 20000)
    self.max_messages.setValue(5000)
    self.max_messages.setSuffix(" 条 / 会话")
    self.max_messages.setToolTip("超过上限的会话会单独标记失败，不会截断后宣称完成；单会话累计上限 20000 条")
    self.incremental = QCheckBox("增量同步")
    self.incremental.setChecked(True)
    self.import_button = self.button("导入 ChatLab", QStyle.StandardPixmap.SP_DialogOpenButton, self.import_export)
    limits = QHBoxLayout()
    limits.addWidget(QLabel("单次上限"))
    limits.addWidget(self.max_messages)
    limits.addWidget(self.incremental)
    limits.addStretch()
    limits.addWidget(self.import_button)
    advanced.addLayout(limits)
    self.advanced.hide()
    layout.addWidget(self.advanced)
    self.advanced_button.toggled.connect(self.toggle_advanced)
    self.single_session.toggled.connect(self.scope_changed)
    self.period.currentIndexChanged.connect(self.change_period)
    self.start_date.dateChanged.connect(self.date_changed)

    progress_row = QHBoxLayout()
    self.status = QLabel("尚未建立任务")
    self.status.setTextFormat(Qt.TextFormat.PlainText)
    self.status.setWordWrap(True)
    self.status.setMinimumHeight(22)
    self.elapsed = QLabel()
    self.elapsed.setObjectName("mutedText")
    progress_row.addWidget(self.status, 1)
    progress_row.addWidget(self.elapsed)
    layout.addLayout(progress_row)
    self.progress_bar = QProgressBar()
    self.progress_bar.setRange(0, 1)
    self.progress_bar.setValue(0)
    self.progress_bar.setTextVisible(False)
    self.progress_bar.setFixedHeight(6)
    layout.addWidget(self.progress_bar)
    self.batch_counts = QLabel("待开始")
    self.batch_counts.setWordWrap(True)
    self.batch_counts.setObjectName("mutedText")
    self.snapshot_time = QLabel()
    self.snapshot_time.setObjectName("mutedText")
    counts = QHBoxLayout()
    counts.addWidget(self.batch_counts, 1)
    counts.addWidget(self.snapshot_time)
    layout.addLayout(counts)

    self.data_tabs = QTabWidget()
    self.data_tabs.setObjectName("chatDataTabs")
    layout.addWidget(self.data_tabs, 1)
    source_page = QWidget()
    source_layout = QVBoxLayout(source_page)
    source_layout.setContentsMargins(0, 8, 0, 0)
    self.source_table = self.table(["账号", "会话", "消息数", "来源"])
    self.source_table.itemSelectionChanged.connect(self.refresh_attachments)
    source_actions = QHBoxLayout()
    self.remove_button = self.button("移除会话索引", QStyle.StandardPixmap.SP_TrashIcon, self.remove_source)
    source_actions.addWidget(self.remove_button)
    source_actions.addStretch()
    self.semantic_update_button = self.button("更新本地语义索引", QStyle.StandardPixmap.SP_BrowserReload,
                                             self.update_semantic_index)
    self.semantic_update_button.setToolTip("更新全部已导入微信会话和已索引附件正文，不连接 Alpha")
    source_actions.addWidget(self.semantic_update_button)
    source_layout.addLayout(source_actions)
    source_layout.addWidget(self.source_table, 1)
    attachment_page = QWidget()
    attachment_layout = QVBoxLayout(attachment_page)
    attachment_layout.setContentsMargins(0, 8, 0, 0)
    self.attachment_table = self.table(["文件名", "会话", "发送者", "关联状态", "正文索引", "本地路径"])
    self.attachment_table.setSelectionMode(QAbstractItemView.SelectionMode.ExtendedSelection)
    self.attachment_table.setMinimumHeight(230)
    attachment_layout.addWidget(self.attachment_table, 1)
    attachment_actions = QHBoxLayout()
    self.bind_button = self.button("关联本地文件", QStyle.StandardPixmap.SP_FileLinkIcon, self.bind_selected)
    self.open_attachment_button = self.button("打开附件", QStyle.StandardPixmap.SP_DialogOpenButton, self.open_attachment)
    self.index_attachments_button = self.button("索引所选正文", QStyle.StandardPixmap.SP_FileDialogContentsView,
                                                self.index_selected_attachments)
    self.folder_button = self.button("添加附件目录", QStyle.StandardPixmap.SP_DirOpenIcon, host.add_folder)
    self.all_attachments_button = self.button("全部附件", QStyle.StandardPixmap.SP_FileDialogListView, self.show_all_attachments)
    for control in (self.bind_button, self.folder_button, self.all_attachments_button):
        control.setAccessibleName(control.text())
        control.setToolTip(control.text())
        control.setText("")
        control.setFixedWidth(36)
    attachment_actions.addWidget(self.open_attachment_button)
    attachment_actions.addWidget(self.bind_button)
    attachment_actions.addWidget(self.index_attachments_button)
    attachment_actions.addWidget(self.folder_button)
    attachment_actions.addWidget(self.all_attachments_button)
    attachment_actions.addStretch()
    attachment_layout.addLayout(attachment_actions)
    self.task_table = self.table(["会话", "状态", "已读取 / 待重试", "耗时", "说明"])
    self.task_table.setMinimumHeight(230)
    self.data_tabs.addTab(attachment_page, "附件")
    self.data_tabs.addTab(source_page, "已索引会话")
    self.data_tabs.addTab(self.task_table, "任务明细")
    self.setWidget(page)
